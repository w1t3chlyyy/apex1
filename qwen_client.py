from openai import OpenAI
import config

# Qwen (Alibaba Cloud DashScope) предоставляет OpenAI-совместимый REST API,
# поэтому мы используем стандартный пакет `openai`, просто указав другой
# base_url и ключ DashScope/Qwen. Полностью заменяет google-generativeai.
_client = OpenAI(
    api_key=config.QWEN_API_KEY,
    base_url=config.QWEN_BASE_URL,
)


def generate_reply(
    system_prompt: str,
    context: str,
    question: str,
    is_first_message: bool = True,
) -> tuple[str, int]:
    """
    Генерирует ответ клиенту.

    Бот отвечает на любые вопросы: если контекст из базы знаний релевантен —
    использует его как приоритетный источник фактов о компании; если нет —
    отвечает своими общими знаниями, как обычный живой оператор поддержки.

    is_first_message: True, если это первое сообщение клиента в диалоге.
    Раньше модель здоровалась в КАЖДОМ ответе ("Здравствуйте!" и т.п.), т.к.
    каждый вызов идёт "с чистого листа" и не знает, было ли уже приветствие
    в этом диалоге. main.py теперь передаёт этот флаг явно (проверяя,
    было ли раньше сообщение role="assistant" в этом диалоге), а промпт
    ниже запрещает повторные приветствия.

    Эскалация на человека не зависит от порога схожести (similarity), а
    решается самой моделью: если это оправдано (явная просьба позвать
    человека, действия с личным аккаунтом/оплатой/возвратом, жалоба/
    конфликт, либо модель не может дать достоверный ответ без риска ввести
    клиента в заблуждение) — модель должна вернуть РОВНО слово ESCALATE и
    ничего больше. main.py дополнительно проверяет наличие этого слова в
    ответе как защиту на случай, если модель всё же добавит его в текст
    вместе с обычным ответом (см. main.py: is_escalation).

    Возвращает (текст_ответа, total_tokens) — total_tokens нужен main.py,
    чтобы вести учёт расхода бесплатного лимита токенов на бесплатном
    тарифе (см. config.FREE_TIER_TOKEN_LIMIT).
    """
    context_block = f"Контекст из базы знаний компании:\n{context}\n\n" if context else ""

    greeting_rule = (
        "Это ПЕРВОЕ сообщение клиента в этом диалоге — можно один раз "
        "поздороваться (например, «Здравствуйте!»), но это не обязательно."
        if is_first_message
        else
        "Это НЕ первое сообщение клиента в этом диалоге — НЕ здоровайся "
        "снова, не пиши «Здравствуйте», «Добрый день», «Приветствую» и "
        "подобные фразы. Сразу отвечай по существу вопроса."
    )

    prompt = (
        f"{context_block}"
        f"{greeting_rule}\n\n"
        f"Вопрос клиента: {question}\n\n"
        "Инструкция:\n"
        "1. Если вопрос связан с компанией/продуктом и в контексте выше есть "
        "релевантная информация — отвечай строго на её основе.\n"
        "2. Если вопрос бытовой, общий, small talk (приветствие, благодарность, "
        "вопрос не по теме компании и т.п.) — отвечай сам, используя свои "
        "общие знания, дружелюбно и по делу, как обычный живой оператор поддержки.\n"
        "3. Если вопроса про компанию нет в контексте, но ты можешь ответить "
        "разумно и без риска (общие рекомендации, объяснения, помощь) — отвечай сам.\n"
        "4. Переводи диалог на живого менеджера ТОЛЬКО в крайнем случае, если "
        "выполняется хотя бы одно:\n"
        "   - клиент явно просит позвать человека/менеджера/оператора;\n"
        "   - вопрос требует действий с личным аккаунтом, оплатой, возвратом "
        "денег, конфиденциальными данными;\n"
        "   - это жалоба или конфликтная ситуация, которую нужно разбирать "
        "вручную;\n"
        "   - ты не можешь дать достоверный ответ и есть реальный риск ввести "
        "клиента в заблуждение.\n"
        "   В этих случаях твой ОТВЕТ ЦЕЛИКОМ должен состоять РОВНО из одного "
        "слова: ESCALATE — без пояснений, без кавычек, без другого текста до "
        "или после, без знаков препинания. Никогда не пиши слово ESCALATE "
        "внутри обычного ответа клиенту.\n"
        "5. Во всех остальных случаях — отвечай сам, кратко и по существу, на "
        "русском языке, без лишних приветствий и вступлений (см. правило выше)."
    )

    response = _client.chat.completions.create(
        model=config.QWEN_CHAT_MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ],
    )
    text = (response.choices[0].message.content or "").strip()
    total_tokens = getattr(response.usage, "total_tokens", 0) if response.usage else 0
    return text, total_tokens


def embed_text(text: str) -> list[float]:
    response = _client.embeddings.create(
        model=config.QWEN_EMBEDDING_MODEL,
        input=text,
    )
    return response.data[0].embedding
