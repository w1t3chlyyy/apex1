from openai import OpenAI
import config

# Qwen (Alibaba Cloud DashScope) предоставляет OpenAI-совместимый REST API,
# поэтому мы используем стандартный пакет `openai`, просто указав другой
# base_url и ключ DashScope/Qwen. Полностью заменяет google-generativeai.
_client = OpenAI(
    api_key=config.QWEN_API_KEY,
    base_url=config.QWEN_BASE_URL,
)


def generate_reply(system_prompt: str, context: str, question: str) -> str:
    """
    Генерирует ответ клиенту.

    ИЗМЕНЕНО: раньше бот отвечал ТОЛЬКО строго по контексту базы знаний
    (см. main.py, где это решалось порогом similarity), а если контекста
    не было или он был недостаточно похож — сразу эскалировал на
    владельца, даже на банальные бытовые вопросы вроде "привет" или
    "как дела". Теперь бот отвечает на любые вопросы: если контекст из
    базы знаний релевантен — использует его как приоритетный источник
    фактов о компании; если нет — отвечает своими общими знаниями, как
    обычный живой оператор поддержки.

    Эскалация на человека теперь НЕ зависит от порога схожести
    (confidence_threshold/similarity), а решается самой моделью:
    если это оправдано (явная просьба позвать человека, действия с
    личным аккаунтом/оплатой/возвратом, жалоба/конфликт, либо модель не
    может дать достоверный ответ без риска ввести клиента в
    заблуждение) — модель возвращает ровно слово ESCALATE и ничего
    больше. main.py проверяет этот маркер и эскалирует диалог только в
    этом случае.
    """
    context_block = f"Контекст из базы знаний компании:\n{context}\n\n" if context else ""

    prompt = (
        f"{context_block}"
        f"Вопрос клиента: {question}\n\n"
        "Инструкция:\n"
        "1. Если вопрос связан с компанией/продуктом и в контексте выше есть "
        "релевантная информация — отвечай строго на её основе.\n"
        "2. Если вопрос бытовой, общий, small talk (приветствие, благодарность, "
        "вопрос не по теме компании и т.п.) — отвечай сам, используя свои "
        "общие знания, дружелюбно и по делу, как обычный живой оператор поддержки.\n"
        "3. Если вопроса про компанию нет в контексте, но ты можешь ответить "
        "разумно и без риска (общие рекомендации, объяснения, помощь) — отвечай сам.\n"
        "4. Переводи диалог на живого менеджера ТОЛЬКО в крайнем случае, если "
        "выполняется хотя бы одно:\n"
        "   - клиент явно просит позвать человека/менеджера/оператора;\n"
        "   - вопрос требует действий с личным аккаунтом, оплатой, возвратом "
        "денег, конфиденциальными данными;\n"
        "   - это жалоба или конфликтная ситуация, которую нужно разбирать "
        "вручную;\n"
        "   - ты не можешь дать достоверный ответ и есть реальный риск ввести "
        "клиента в заблуждение (например, точные детали именно про компанию, "
        "которых нет в контексте, а вопрос явно требует именно их).\n"
        "   В этих случаях ответь РОВНО одним словом: ESCALATE — без пояснений, "
        "без кавычек, без дополнительного текста, без знаков препинания.\n"
        "5. Во всех остальных случаях — отвечай сам, кратко и по существу, на "
        "русском языке."
    )

    response = _client.chat.completions.create(
        model=config.QWEN_CHAT_MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ],
    )
    return (response.choices[0].message.content or "").strip()


def embed_text(text: str) -> list[float]:
    response = _client.embeddings.create(
        model=config.QWEN_EMBEDDING_MODEL,
        input=text,
    )
    return response.data[0].embedding
